#!/usr/bin/env python3
"""Read-only focused A733 IOMMU v20 translation programming and DT search.

Unlike the broad Stage 8 inventory, finds every TTB use and the exact write
macro, and searches all DTS/DTSI names (not just A733-named candidates).
"""
from pathlib import Path
import argparse,hashlib,re,sys

ROOT=Path("/root/opi3w-m2-work/linux-618-hdmi-stage4/artifacts")
K=ROOT/"iommu-v20-port-stage1-kcflags/linux"
V=Path("/root/opi3w-vendor-6698-work/kernel/bsp")
EXPECTED="aa78ce2829693be1c27e93647244f50dd86dc4f386930b2301ba8990b7d19b53"

def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def snippets(p,terms,radius=9,max_matches=24):
    lines=p.read_text(errors="replace").splitlines()
    hits=[i for i,line in enumerate(lines) if any(t.search(line) for t in terms)]
    result=["FILE "+str(p),"SHA256 "+sha(p),"MATCHES "+str(len(hits))]
    indices=set()
    for i in hits[:max_matches]:
        indices.update(range(max(0,i-radius),min(len(lines),i+radius+1)))
    last=-2
    for i in sorted(indices):
        if i>last+1:result.append("...")
        result.append(str(i+1)+": "+lines[i][:250])
        last=i
    if len(hits)>max_matches:result.append("TRUNCATED "+str(len(hits)-max_matches))
    return result

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("--kernel",type=Path,default=K)
    ap.add_argument("--vendor",type=Path,default=V)
    ap.add_argument("--out",type=Path,default=ROOT/"iommu-v20-stage8b-focused.txt")
    a=ap.parse_args()
    if a.out.exists():ap.error("report already exists; select a fresh --out")
    driver=a.kernel/"drivers/iommu/aw-v20/sunxi-iommu-v2.c"
    if not driver.is_file() or sha(driver)!=EXPECTED:
        ap.error("staged driver does not match audited SHA256")
    regs=[r"\bIOMMU_TTB_REG\b",r"\bWRITE_EQUAL_REG\b",
          r"^#define IOMMU_PER_SET_ADDR_SIZE",r"^#define IOMMU_HW_SET_COUNT",
          r"\bIOMMU_MIC_BYP_REG\b",r"^static int sunxi_iommu_hw_init",
          r"^void sunxi_enable_device_iommu",r"^static void __sunxi_enable_device_iommu_unlocked",
          r"^static int sunxi_iommu_of_xlate"]
    # Regex patterns explicitly bounded to the small set of decisive sites.
    terms=[re.compile(x) for x in regs]
    out=["A733 v20 IOMMU focused topology audit","READ ONLY; hardware activation BLOCKED"]
    out+=snippets(driver,terms,10,28)
    roots=[a.vendor/"arch/arm64/boot/dts",a.kernel/"arch/arm64/boot/dts"]
    # Also scan vendor's conventional DTS directories when available.
    for extra in ("arch/arm/boot/dts","device/config/chips"):
        candidate=a.vendor/extra
        if candidate.is_dir():roots.append(candidate)
    keys=re.compile(r"iommu|03900000|#iommu-cells|allwinner,iommu-v20|\biommus\s*=",re.I)
    scanned=0; matched=0
    for directory in roots:
        if not directory.is_dir():
            out.append("MISSING DTS ROOT "+str(directory));continue
        files=sorted(p for p in directory.rglob("*") if p.is_file() and p.suffix in (".dts",".dtsi"))
        out.append("DTS ROOT "+str(directory)+" FILES "+str(len(files)))
        for path in files:
            # Guard against pathological oversized autogenerated inputs.
            if path.stat().st_size>5_000_000:
                out.append("SKIPPED OVERSIZE "+str(path));continue
            scanned+=1
            try:src=path.read_text(errors="replace")
            except OSError:continue
            if keys.search(src):
                matched+=1
                out+=snippets(path,[keys],5,18)
    out.extend(["DTS FILES SCANNED "+str(scanned),"DTS FILES MATCHED "+str(matched),
                "NOTE: DTS not found here does not prove vendor firmware lacks the node.",
                "NO CODE, DTB, BOOT OR FIRMWARE CHANGES."])
    a.out.parent.mkdir(parents=True,exist_ok=True)
    a.out.write_text("\n".join(out)+"\n")
    print("REPORT:",a.out)
    print("DTS files scanned:",scanned,"matched:",matched)
    print("Hardware activation remains BLOCKED")
if __name__=="__main__":main()
